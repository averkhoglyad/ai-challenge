package io.averkhogliad.ai.challenge.week2.domain.model

/**
 * Этап выполнения команды в FSM (Finite State Machine).
 *
 * Представляет крупную фазу выполнения сложной команды.
 * Каждая команда определяет свой набор этапов и шагов внутри них.
 *
 * ## Жизненный цикл
 * 1. Создание состояния при вызове команды
 * 2. Последовательное прохождение этапов
 * 3. Уничтожение состояния после завершения или отмены
 */
enum class CommandStage {
    /**
     * Этап планирования: проверка условий, сбор контекста, подготовка данных.
     * Для команды :plan — проверка открытой задачи, запрос description, сбор фактов из LTM.
     */
    PLANNING,

    /**
     * Этап выполнения: основная работа команды (запросы к LLM, вычисления и т.д.).
     * Для команды :plan — формирование промпта, запрос к LLM, парсинг ответа.
     */
    EXECUTION,

    /**
     * Этап валидации: проверка результата, ожидание подтверждения пользователя.
     * Для команды :plan — показ шагов пользователю, ожидание y/n/edit.
     */
    VALIDATION,

    /**
     * Этап завершения: сохранение результатов, очистка состояния.
     * Для команды :plan — сохранение шагов в WM, завершение команды.
     */
    DONE
}
