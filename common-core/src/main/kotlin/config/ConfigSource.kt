package io.averkhogliad.ai.challenge.utils.config

/**
 * Абстракция над источником конфигурации.
 *
 * Представляет собой фабрику, которая может загрузить [Config] из некоторого источника
 * (файл, classpath, переменные окружения и т.д.).
 *
 * Источники могут быть опциональными — если источник недоступен, метод [load] возвращает `null`.
 *
 * Примеры реализаций:
 * - [ClasspathConfigSource] — загрузка из classpath-ресурса;
 * - [FileConfigSource] — загрузка из файла на диске.
 */
interface ConfigSource {

    /**
     * Загружает конфигурацию из источника.
     *
     * @return загруженный [Config] или `null`, если источник недоступен или не существует.
     */
    fun load(): Config?
}
